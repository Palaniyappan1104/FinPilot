def _get_groq_client():
    """Return a configured Groq client or raise 503."""
    if not _GROQ_AVAILABLE:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="groq package is not installed.",
        )

    api_key = os.getenv("GROQ_API_KEY", "")

    if not api_key:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="GROQ_API_KEY is not configured in environment.",
        )

    return Groq(api_key=api_key)


def _generate_text(
    prompt: str,
    system: str = "",
    max_tokens: int = 2048,
    temperature: float = 0.4,
    model: Optional[str] = None,
) -> str:
    """Call a Groq model and return plain text response.

    Falls back to the same call without ``temperature`` if the target model
    rejects that parameter, then to the specialist model if the requested
    model is unavailable on this account.
    """

    client = _get_groq_client()
    model = model or SPECIALIST_MODEL

    messages: List[Dict[str, str]] = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    attempts: List[Dict[str, Any]] = [
        {
            "model": model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        },
        {
            "model": model,
            "messages": messages,
            "max_tokens": max_tokens,
        },
    ]
    if model != SPECIALIST_MODEL:
        attempts.append({
            "model": SPECIALIST_MODEL,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        })

    last_error: Optional[Exception] = None
    for kwargs in attempts:
        try:
            response = client.chat.completions.create(**kwargs)
            text = response.choices[0].message.content or ""
            if text.strip():
                return text
        except Exception as exc:  # try the next fallback shape
            last_error = exc
            continue

    if last_error:
        raise last_error
    return ""


