def _build_synthesis_prompt(
    request: AnalyzeRequest,
    md: Dict[str, Any],
    briefs: List[Dict[str, str]],
    resolution_notes: List[str],
) -> str:
    parts = [
        "=== INVESTOR INPUT ===",
        _profile_text(request),
        "",
        f"Resolved instrument: {md.get('ticker')} / "
        f"{md.get('long_name') or request.target_company or 'name unavailable'}",
        "",
        "=== VERIFIED DATA ===",
        _format_price_facts(md),
        "",
        _format_fundamental_facts(md),
        "",
        _format_headlines(md),
        "",
        "=== DATA GAPS RECORDED DURING COLLECTION ===",
    ]
    gaps = list(md.get("notes", [])) + list(resolution_notes)
    parts.append(
        "\n".join(f"- {g}" for g in gaps)
        if gaps else "- None; all requested data was retrieved."
    )

    parts.append("\n=== SPECIALIST RESEARCH BRIEFS ===")
    for b in briefs:
        parts.append(f"\n--- {b['name']} (status: {b['status']}) ---\n{b['brief']}")

    parts.append("\n=== DATA SOURCES ACTUALLY USED ===")
    parts.append("\n".join(f"- {s}" for s in _collect_sources(md)))

    parts.append(
        "\nSynthesise the above into the required JSON research note. Be thorough; "
        "this report is read by a professional investor."
    )
    return "\n".join(parts)


