# Indicator helpers (computed from real price history, never guessed)
# ---------------------------------------------------------------------------

def _sma(values: List[float], window: int) -> Optional[float]:
    if len(values) < window:
        return None
    return sum(values[-window:]) / window


def _ema_series(values: List[float], window: int) -> List[float]:
    if not values:
        return []
    k = 2.0 / (window + 1.0)
    out = [values[0]]
    for v in values[1:]:
        out.append(v * k + out[-1] * (1 - k))
    return out


def _rsi(values: List[float], period: int = 14) -> Optional[float]:
    if len(values) < period + 1:
        return None
    gains, losses = [], []
    for prev, cur in zip(values[-(period + 1):-1], values[-period:]):
        change = cur - prev
        gains.append(max(change, 0.0))
        losses.append(max(-change, 0.0))
    avg_gain = sum(gains) / period
    avg_loss = sum(losses) / period
    if avg_loss == 0:
        return 100.0
    rs = avg_gain / avg_loss
    return 100.0 - (100.0 / (1.0 + rs))


def _macd(
    values: List[float],
) -> Tuple[Optional[float], Optional[float], Optional[float]]:
    if len(values) < 35:
        return None, None, None
    ema12 = _ema_series(values, 12)
    ema26 = _ema_series(values, 26)
    macd_line = [a - b for a, b in zip(ema12[-len(ema26):], ema26)]
    signal = _ema_series(macd_line, 9)
    return macd_line[-1], signal[-1], macd_line[-1] - signal[-1]


def _annualised_volatility(values: List[float]) -> Optional[float]:
    if len(values) < 30:
        return None
    rets = [
        (b - a) / a
        for a, b in zip(values[:-1], values[1:])
        if a
    ]
    if len(rets) < 20:
        return None
    return statistics.pstdev(rets[-252:]) * (252 ** 0.5) * 100.0


def _num(value: Any) -> Optional[float]:
    try:
        if value is None:
            return None
        f = float(value)
        if f != f:  # NaN
            return None
        return f
    except (TypeError, ValueError):
        return None


def _fmt(value: Optional[float], suffix: str = "", digits: int = 2) -> str:
    if value is None:
        return "unavailable"
    return f"{value:,.{digits}f}{suffix}"


def _fmt_big(value: Optional[float]) -> str:
    if value is None:
        return "unavailable"
    for cutoff, unit in ((1e12, "T"), (1e9, "B"), (1e6, "M")):
        if abs(value) >= cutoff:
            return f"{value / cutoff:,.2f}{unit}"
    return f"{value:,.0f}"


