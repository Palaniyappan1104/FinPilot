_CLARIFY_SYSTEM = """You are FinPilot's Clarification Agent.
Read the user's financial query and generate exactly 1 or 2 smart, concise
clarifying questions that will help produce a better investment analysis.

Rules:
- Only ask what is genuinely missing from the query.
- If investment horizon is not mentioned, ask it.
- If risk tolerance is not mentioned, ask it.
- If the query is already very specific, ask only 1 question.
- Do NOT ask about the company/ticker if already mentioned.
- Keep questions short (under 15 words each).
- Respond ONLY as a valid JSON object, no extra text:
  {
    "questions": ["Question 1?", "Question 2?"],
    "detected_ticker": "AAPL",
    "detected_company": "Apple Inc."
  }
- detected_ticker and detected_company should be null if not found in the query.
"""


@router.post(
    "/clarify",
    response_model=ClarifyResponse,
    summary="Generate clarifying questions for a user query",
    description=(
        "Sends the raw user query to Groq and returns 1-2 targeted "
        "clarifying questions to sharpen the investment analysis."
    ),
    operation_id="demoClarifyQuery",
)
async def clarify_query(request: ClarifyRequest) -> ClarifyResponse:
    """Generate clarifying questions from Groq for the given query."""
    prompt = f"User Query: {request.query}"
    try:
        raw = _generate_text(
            prompt=prompt,
            system=_CLARIFY_SYSTEM,
            max_tokens=CLARIFY_TOKENS,
            model=SPECIALIST_MODEL,
        )
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Groq clarification call failed: {exc}",
        ) from exc

    # Strip markdown fences if Groq wraps in ```json
    cleaned = re.sub(r"```(?:json)?", "", raw).strip().strip("`").strip()
    try:
        parsed: Dict[str, Any] = json.loads(cleaned)
    except json.JSONDecodeError:
        # Fallback: pull out anything that looks like a question
        qs = re.findall(r'"([^"]+\?)"', cleaned)
        parsed = {
            "questions": qs[:2] if qs else ["What is your investment horizon?"],
            "detected_ticker": None,
            "detected_company": None,
        }

    return ClarifyResponse(
        questions=parsed.get("questions", ["What is your investment horizon?"])[:2],
        detected_ticker=parsed.get("detected_ticker"),
        detected_company=parsed.get("detected_company"),
    )


