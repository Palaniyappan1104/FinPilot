def _format_headlines(md: Dict[str, Any]) -> str:
    if not md.get("headlines"):
        return (
            "PROVIDER HEADLINES: none returned. Treat recent news flow and "
            "analyst positioning as unavailable."
        )
    lines = ["PROVIDER HEADLINES (real, retrieved from the market data provider):"]
    for h in md["headlines"]:
        lines.append(f"- [{h['published']}] {h['title']} ({h['publisher']})")
    return "\n".join(lines)


def _collect_sources(md: Dict[str, Any]) -> List[str]:
    """Report only the data sources actually used."""
    sources: List[str] = []
    if md.get("price_available") or md.get("fundamentals_available"):
        sources.append("Yahoo Finance market data (via yfinance)")
    publishers = sorted({
        h.get("publisher", "").strip()
        for h in md.get("headlines", [])
        if h.get("publisher")
    })
    sources.extend(publishers)
    if not sources:
        sources.append("No external data source was reachable for this analysis.")
    return sources


