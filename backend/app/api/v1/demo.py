@router.post(
    "/analyze",
    response_model=AnalyzeResponse,
    summary="Run a full multi-stage AI research pipeline",
    description=(
        "Resolves the instrument, retrieves verified yfinance market data and "
        "computes indicators, runs five specialist research stages concurrently, "
        "then synthesises a long-form structured investment research report. "
        "This demo path bypasses the LangGraph pipeline entirely."
    ),
    operation_id="demoAnalyzeCompany",
)
async def analyze_company(request: AnalyzeRequest) -> AnalyzeResponse:
    """Run the research pipeline and return a synthesised research note."""

    # --- Stage 0: resolve instrument + collect verified data --------------
    ticker, company, resolution_notes = await asyncio.to_thread(
        _resolve_instrument, request.query, request.ticker, request.target_company
    )
    market_data = await asyncio.to_thread(_fetch_market_data, ticker)
    market_data["ticker"] = ticker

    # --- Stages 1-5: concurrent specialist research -----------------------
    try:
        briefs = await _run_research(request, market_data)
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Research pipeline failed: {exc}",
        ) from exc

    if all(b["status"] == "failed" for b in briefs):
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="All research stages failed; no report could be produced.",
        )

    # --- Stage 6: synthesis on Compound Mini ------------------------------
    synthesis_prompt = _build_synthesis_prompt(
        request, market_data, briefs, resolution_notes
    )

    try:
        raw = await asyncio.to_thread(
            _generate_text,
            synthesis_prompt,
            _ANALYSIS_SYSTEM,
            SYNTHESIS_TOKENS,
            0.35,
            ORCHESTRATOR_MODEL,
        )
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Groq synthesis call failed: {exc}",
        ) from exc

    cleaned = re.sub(r"```(?:json)?", "", raw).strip().strip("`").strip()
    try:
        data: Dict[str, Any] = json.loads(cleaned)
    except json.JSONDecodeError:
        # Salvage the outermost JSON object if the model added stray prose.
        match = re.search(r"\{.*\}", cleaned, re.DOTALL)
        if not match:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Failed to parse synthesis JSON response. Preview: {raw[:400]}",
            )
        try:
            data = json.loads(match.group(0))
        except json.JSONDecodeError as exc:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=(
                    f"Failed to parse synthesis JSON response: {exc}. "
                    f"Preview: {raw[:400]}"
                ),
            ) from exc

    final_ticker = data.get("ticker") or ticker or "N/A"
    final_company = (
        data.get("company")
        or market_data.get("long_name")
        or company
        or request.target_company
        or "Unknown Company"
    )

    # Agent statuses describe what the pipeline actually did.
    agent_statuses = [
        AgentStatus(name=b["name"], status=b["status"], summary=b["summary"])
        for b in briefs
    ]
    agent_statuses.append(
        AgentStatus(
            name="Synthesis Agent",
            status="completed",
            summary="Specialist briefs reconciled into the final research note.",
        )
    )

    raw_markdown = _render_markdown(
        data, market_data, briefs, final_ticker, final_company
    )

    key_metrics = data.get("key_metrics") or {}
    if not isinstance(key_metrics, dict):
        key_metrics = {}
    key_metrics = {str(k): str(v) for k, v in key_metrics.items()}

    sources = data.get("sources") or _collect_sources(market_data)
    if not isinstance(sources, list):
        sources = [str(sources)]

    return AnalyzeResponse(
        ticker=final_ticker,
        company=final_company,
        executive_summary=data.get("executive_summary", ""),
        technical_outlook=data.get("technical_outlook", ""),
        fundamental_view=data.get("fundamental_view", ""),
        news_sentiment=data.get("news_sentiment", ""),
        risk_assessment=data.get("risk_assessment", ""),
        final_verdict=data.get("final_verdict", ""),
        confidence=data.get("confidence", "Medium"),
        disclaimer=data.get(
            "disclaimer",
            (
                "This report is for informational purposes only "
                "and does not constitute financial advice."
            ),
        ),
        agent_statuses=agent_statuses,
        raw_markdown=raw_markdown,
        investor_profile=data.get("investor_profile", ""),
        valuation_view=data.get("valuation_view", ""),
        scenario_analysis=data.get("scenario_analysis", ""),
        catalysts_to_watch=data.get("catalysts_to_watch", ""),
        data_availability=data.get("data_availability", ""),
        key_metrics=key_metrics,
        sources=[str(s) for s in sources],
        research_briefs={b["name"]: b["brief"] for b in briefs},
    )
