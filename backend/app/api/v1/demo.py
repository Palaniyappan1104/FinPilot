async def _run_research(
    request: AnalyzeRequest, md: Dict[str, Any]
) -> List[Dict[str, str]]:
    """Run the five research stages concurrently, tolerating individual failures."""

    stages = [
        ("Conversation Agent", _stage_profile),
        ("Technical Analyst", _stage_technical),
        ("Fundamental Analyst", _stage_fundamental),
        ("News & Sentiment Agent", _stage_news),
        ("Risk Assessment Agent", _stage_risk),
    ]

    results = await asyncio.gather(
        *(asyncio.to_thread(fn, request, md) for _, fn in stages),
        return_exceptions=True,
    )

    output: List[Dict[str, str]] = []
    for (name, _), result in zip(stages, results):
        if isinstance(result, Exception):
            output.append({
                "name": name,
                "status": "failed",
                "summary": f"Stage could not complete: {result}",
                "brief": (
                    f"{name} produced no output; "
                    "treat this dimension as unresearched."
                ),
            })
        else:
            output.append(result)
    return output


