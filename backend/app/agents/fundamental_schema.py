"""Normalized domain and structured output schemas for Fundamental Analyst Agent.

Phase 6.3 defines the input and structured output models for interpreting
deterministic FundamentalMetrics:
- FundamentalAnalystInput: Carries FundamentalMetrics, investor constraints,
  and CIO guidance.
- DimensionAssessment: Structured evaluation per fundamental dimension with
  supporting metrics.
- FundamentalAnalysisOutput: Comprehensive structured fundamental assessment.
"""

from typing import List, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

from app.models.fundamental_metrics import FundamentalMetrics

DimensionRating = Literal["strong", "moderate", "weak", "neutral", "insufficient_data"]
OverallAssessmentRating = Literal[
    "favorable", "neutral", "unfavorable", "insufficient_data"
]

# Set of all valid deterministic metric attribute names from FundamentalMetrics
