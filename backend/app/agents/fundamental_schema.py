    "both_periods_deficit",
    "eps_turnaround",
    "eps_deficit_turnaround",
    "both_periods_eps_deficit",
    # Profitability
    "operating_margin",
    "net_profit_margin",
    "roe",
    "roa",
    "negative_equity",
    # Leverage
    "total_debt",
    "total_equity",
    "cash_and_equivalents",
